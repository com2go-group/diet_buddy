// Builds landing/privacy.html, terms.html and delete-account.html from the same texts the app
// shows (src/features/legal/*.en.ts), so the website and the app never disagree.
//
//   npm run landing:legal
//
// If EXPO_PUBLIC_LEGAL_COMPANY / _ADDRESS / _EMAIL / _COUNTRY are set, they are written into
// the pages. Otherwise the pages keep placeholders that landing/config.js fills in the browser.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { DELETE_ACCOUNT } from '../../src/features/legal/deleteAccount.en.ts';
import { PRIVACY_POLICY } from '../../src/features/legal/privacy.en.ts';
import { TERMS_OF_SERVICE } from '../../src/features/legal/terms.en.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const out = join(root, 'landing');

const PLACEHOLDERS = {
  company: [process.env.EXPO_PUBLIC_LEGAL_COMPANY, '[company name]'],
  address: [process.env.EXPO_PUBLIC_LEGAL_ADDRESS, '[registered address]'],
  email: [process.env.EXPO_PUBLIC_LEGAL_EMAIL, '[privacy email]'],
  country: [process.env.EXPO_PUBLIC_LEGAL_COUNTRY, '[country]'],
};

const escape = (s) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** Escapes text and turns {{company}}-style placeholders into fillable spans. */
function text(s) {
  return escape(s).replace(/\{\{(\w+)\}\}/g, (match, key) => {
    const entry = PLACEHOLDERS[key];
    if (!entry) return match;
    const value = entry[0];
    return value ? escape(value) : `<span data-legal="${key}">${entry[1]}</span>`;
  });
}

const block = (b) =>
  typeof b === 'string'
    ? `<p>${text(b)}</p>`
    : `<ul>\n${b.list.map((i) => `            <li>${text(i)}</li>`).join('\n')}\n          </ul>`;

const longDate = (iso) =>
  new Date(`${iso}T12:00:00Z`).toLocaleDateString('en-GB', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
    timeZone: 'UTC',
  });

const BRAND = `<a class="brand" href="index.html" aria-label="DietBuddy home">
          <span class="brand-tile" aria-hidden="true">
            <svg viewBox="0 0 24 24" width="20" height="20">
              <polygon points="13 2 3 14 12 14 11 22 21 10 12 10 13 2" />
            </svg>
          </span>
          <span class="brand-word">Diet<span>Buddy</span></span>
        </a>`;

function page(doc, file, description) {
  const sections = doc.sections
    .map(
      (s) => `        <section>
          <h2>${text(s.heading)}</h2>
          ${s.blocks.map(block).join('\n          ')}
        </section>`,
    )
    .join('\n');
  return `<!doctype html>
<!-- Generated by scripts/landing/build-legal-pages.mjs from src/features/legal. Don't edit by hand. -->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${escape(doc.title)} · DietBuddy</title>
    <meta name="description" content="${escape(description)}" />
    <meta name="theme-color" content="#F59E0B" />
    <link rel="icon" href="assets/favicon.svg" type="image/svg+xml" />
    <link rel="stylesheet" href="styles.css" />
    <script src="config.js" defer></script>
    <script src="main.js" defer></script>
  </head>
  <body>
    <a class="skip" href="#main">Skip to content</a>
    <header class="site-header">
      <div class="container header-row">
        ${BRAND}
        <a class="btn btn-primary btn-small" href="index.html#download">Get the app</a>
      </div>
    </header>
    <main id="main" class="legal">
      <article class="container narrow">
        <p class="eyebrow">Legal</p>
        <h1>${escape(doc.title)}</h1>
        <p class="legal-updated">Last updated ${longDate(doc.updated)}</p>
        ${doc.intro.map(block).join('\n        ')}
${sections}
        <p class="legal-back"><a href="index.html">← Back to DietBuddy</a></p>
      </article>
    </main>
    <footer class="site-footer">
      <div class="container footer-row">
        ${BRAND}
        <nav aria-label="Legal">
          <ul class="footer-links">
            <li><a data-link="privacy" href="privacy.html"${file === 'privacy.html' ? ' aria-current="page"' : ''}>Privacy Policy</a></li>
            <li><a data-link="terms" href="terms.html"${file === 'terms.html' ? ' aria-current="page"' : ''}>Terms of Service</a></li>
            <li><a data-link="deleteAccount" href="delete-account.html"${file === 'delete-account.html' ? ' aria-current="page"' : ''}>Delete your account</a></li>
            <li><a data-link="contact" href="index.html">Contact</a></li>
          </ul>
        </nav>
        <p class="copyright">© <span data-year>2026</span> <span data-company>DietBuddy</span></p>
      </div>
    </footer>
  </body>
</html>
`;
}

const pages = [
  [PRIVACY_POLICY, 'privacy.html', 'How DietBuddy collects, uses and protects your personal data.'],
  [TERMS_OF_SERVICE, 'terms.html', 'The terms for using the DietBuddy app.'],
  [DELETE_ACCOUNT, 'delete-account.html', 'How to delete your DietBuddy account and all its data.'],
];
for (const [doc, file, description] of pages) {
  writeFileSync(join(out, file), page(doc, file, description));
  console.log(`landing/${file}`);
}
